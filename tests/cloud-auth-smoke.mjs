// Explicitly target a development deployment. Signing material is read only from an ignored file.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { ConvexHttpClient, ConvexClient } from 'convex/browser';
import { api } from '../convex/_generated/api.js';
import { signUserToken } from '../lib/auth-token.ts';
import {mergeRecipes} from '../lib/recipes.ts';
const url = process.env.PANTRY_TEST_CONVEX_URL;
if (!url || !process.env.PANTRY_TEST_SIGNING_FILE || !process.env.PANTRY_TEST_ISSUER) throw Error('Explicit development target and test signing file required');
const { privateJwk } = JSON.parse(readFileSync(process.env.PANTRY_TEST_SIGNING_FILE, 'utf8'));
const subject = 'integration-check-' + crypto.randomUUID();
const token = await signUserToken(subject, process.env.PANTRY_TEST_ISSUER, privateJwk);
const client = new ConvexHttpClient(url, { logger: false }); client.setAuth(token);
const sessionId = await client.mutation(api.accounts.ensure, {});
assert.equal(await client.mutation(api.accounts.ensure, {}), sessionId);
await client.mutation(api.plans.change, { sessionId, operation: 'samples' });
await client.mutation(api.plans.change, { sessionId, operation: 'people', people: 4 });
const fresh = new ConvexHttpClient(url, { logger: false }); fresh.setAuth(token);
assert.equal((await fresh.query(api.plans.get, { sessionId })).people, 4);
assert.equal((await fresh.query(api.plans.get, { sessionId })).recipes.length, 2);
const originalRecipe=(await fresh.query(api.plans.get,{sessionId})).recipes[0];
const previousPlan=await fresh.query(api.plans.get,{sessionId});const groceries=mergeRecipes(previousPlan.recipes,previousPlan.people);
const cucumber=groceries.find(item=>item.name==='黄瓜'),pasta=groceries.find(item=>item.name==='意大利面');
for(const item of [cucumber,pasta])await fresh.mutation(api.plans.change,{sessionId,operation:'check',key:item.key,checked:true});
const updatedRecipe={...originalRecipe,name:'Edited integration meal',servings:4};
await fresh.mutation(api.plans.change,{sessionId,operation:'edit',recipe:updatedRecipe,originalRecipe});
assert.equal((await client.query(api.plans.get,{sessionId})).recipes[0].name,'Edited integration meal');
const editedPlan=await client.query(api.plans.get,{sessionId});assert.ok(editedPlan.checked.includes(cucumber.key));assert.ok(!editedPlan.checked.includes(pasta.key));
await assert.rejects(client.mutation(api.plans.change,{sessionId,operation:'edit',recipe:{...updatedRecipe,name:'stale'},originalRecipe}));
const asWritten={...updatedRecipe,id:crypto.randomUUID(),name:'Recipe without servings',servings:null,sample:false};
await fresh.mutation(api.plans.change,{sessionId,operation:'add',recipe:asWritten});
assert.equal((await client.query(api.plans.get,{sessionId})).recipes.find(recipe=>recipe.id===asWritten.id).servings,null);
const choice={...updatedRecipe,id:crypto.randomUUID(),name:'Optional ingredient check',ingredients:[{name:'water',quantity:100,unit:'ml',category:'其他',note:'',choiceGroup:'drink',included:false},{name:'milk',quantity:100,unit:'ml',category:'肉蛋奶',note:'',choiceGroup:'drink',included:true}]};
await fresh.mutation(api.plans.change,{sessionId,operation:'add',recipe:choice});
const recoveredChoice=(await client.query(api.plans.get,{sessionId})).recipes.find(recipe=>recipe.id===choice.id);assert.equal(recoveredChoice.ingredients[0].included,false);assert.equal(mergeRecipes([recoveredChoice],4).length,1);
await assert.rejects(fresh.mutation(api.plans.change,{sessionId,operation:'edit',originalRecipe:choice,recipe:{...choice,ingredients:choice.ingredients.map(row=>({...row,included:true}))}}));
const stranger = new ConvexHttpClient(url, { logger: false });
await assert.rejects(stranger.query(api.plans.get, { sessionId }));
stranger.setAuth(await signUserToken('another-' + subject, process.env.PANTRY_TEST_ISSUER, privateJwk));
await assert.rejects(stranger.query(api.plans.get, { sessionId }));
await assert.rejects(stranger.mutation(api.plans.change, { sessionId, operation: 'people', people: 20 }));
await assert.rejects(stranger.mutation(api.plans.change,{sessionId,operation:'edit',recipe:updatedRecipe,originalRecipe:updatedRecipe}));
const live = new ConvexClient(url, { logger: false }); live.setAuth(async () => token);
let resolveInitial, resolveChange;
const initial = new Promise(resolve => { resolveInitial = resolve; });
const changed = new Promise(resolve => { resolveChange = resolve; });
const timer = setTimeout(() => { console.error('Realtime check timed out'); process.exit(1); }, 20000);
const unsubscribe = live.onUpdate(api.plans.get, { sessionId }, plan => { if (plan.people === 4) resolveInitial(); if (plan.people === 3) resolveChange(); });
try {
  await initial;
  await fresh.mutation(api.plans.change, { sessionId, operation: 'people', people: 3 });
  await changed;
  for (const recipe of (await fresh.query(api.plans.get, { sessionId })).recipes) await fresh.mutation(api.plans.change, { sessionId, operation: 'remove', recipeId: recipe.id });
  console.log(JSON.stringify({ authenticatedSave: true, freshClientRecovery: true,unknownServingsSaved:true,unrelatedChecksRetained:true,changedCheckCleared:true,choicesPersisted:true,twoAlternativesDenied:true,editSaved:true,staleEditDenied:true,otherAccountEditDenied:true, anonymousDenied: true, otherAccountDenied: true, realtimeUpdate: true, fixtureRecipesRemoved: true }));
} finally { clearTimeout(timer); unsubscribe(); await live.close(); }
